// Package program_details holds the shared rules for the presentation details
// of a training plan that are not part of the prescription itself: the cover
// image key and the name, description and muscle-group focus of a training
// day. Platform plans (generic_programs) and trainer plans (program_structure,
// programs) validate through the same functions so both builders accept the
// same values.
package program_details

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
	"unicode/utf8"

	"ryze/backend/models"
)

// ErrInvalid is wrapped by every validation failure of this package.
var ErrInvalid = errors.New("invalid program details")

const (
	// MaxDayNameLength caps a training-day name (matches the column).
	MaxDayNameLength = 80
	// MaxDayDescriptionLength caps a training-day description (matches the
	// column).
	MaxDayDescriptionLength = 1000
)

// FocusValues is the closed muscle-group vocabulary a training day can focus
// on. It matches the chk_program_workouts_focus database constraint.
var FocusValues = []string{
	"full_body", "upper_body", "lower_body", "push", "pull", "legs",
	"chest", "back", "shoulders", "arms", "core", "glutes", "cardio", "mobility",
}

// Cover image folders inside the uploads directory, one per catalogue
// category (owner request, 2026-11-14).
const (
	CoverFolderGeneric = "generic"
	CoverFolderLevel1  = "l1"
	CoverFolderLevel2  = "l2"
)

var coverKeyPattern = regexp.MustCompile(`^programs/(generic|l1|l2)/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$`)

// CoverFolder returns the uploads folder of a plan's cover image: the folder of
// its catalogue category. Platform plans use their product family; trainer
// plans (family generic) use their commercial type, matching the catalogue
// price they sell at.
func CoverFolder(productType, programType string) string {
	switch models.CatalogPriceMinorUnits(productType, programType) {
	case models.PremiumLevel1PriceMinorUnits:
		return CoverFolderLevel1
	case models.PremiumLevel2PriceMinorUnits:
		return CoverFolderLevel2
	default:
		return CoverFolderGeneric
	}
}

// ValidateCoverKey accepts an empty key (no cover) or a key generated by the
// uploads store inside the expected category folder.
func ValidateCoverKey(folder, key string) error {
	key = strings.TrimSpace(key)
	if key == "" {
		return nil
	}
	if !coverKeyPattern.MatchString(key) {
		return fmt.Errorf("%w: unknown cover image", ErrInvalid)
	}
	if !strings.HasPrefix(key, "programs/"+folder+"/") {
		return fmt.Errorf("%w: the cover image belongs to another category", ErrInvalid)
	}
	return nil
}

// OptionalCover maps an empty key to nil.
func OptionalCover(key string) *string {
	key = strings.TrimSpace(key)
	if key == "" {
		return nil
	}
	return &key
}

// ValidateWorkoutDetails validates a training day's name, description and
// focus. Every field is optional; an empty focus means "not set".
func ValidateWorkoutDetails(name, description, focus string) error {
	if utf8.RuneCountInString(strings.TrimSpace(name)) > MaxDayNameLength {
		return fmt.Errorf("%w: a training day name is capped at %d characters", ErrInvalid, MaxDayNameLength)
	}
	if utf8.RuneCountInString(description) > MaxDayDescriptionLength {
		return fmt.Errorf("%w: a training day description is capped at %d characters", ErrInvalid, MaxDayDescriptionLength)
	}
	focus = strings.TrimSpace(focus)
	if focus == "" {
		return nil
	}
	for _, candidate := range FocusValues {
		if focus == candidate {
			return nil
		}
	}
	return fmt.Errorf("%w: unsupported training day focus", ErrInvalid)
}

// OptionalFocus maps an empty focus to nil.
func OptionalFocus(focus string) *string {
	focus = strings.TrimSpace(focus)
	if focus == "" {
		return nil
	}
	return &focus
}

// PublicUploadsPrefix is the URL path the API serves public uploads from.
const PublicUploadsPrefix = "/uploads"

// CoverURL maps a stored cover key to its public path, or "" without a cover.
func CoverURL(key *string) string {
	if key == nil || strings.TrimSpace(*key) == "" {
		return ""
	}
	return PublicUploadsPrefix + "/" + *key
}

// LevelValues is the controlled audience vocabulary of training plans.
var LevelValues = []string{"Beginner", "Intermediate", "Advanced"}

// TrainingTypeValues is the controlled training-goal vocabulary of training
// plans (the marketplace "goal" filter).
var TrainingTypeValues = []string{"Hypertrophy", "Strength", "HYROX", "CrossFit", "Fat Loss", "At Home"}

// ValidateCatalogMetadata validates the optional level, training goal,
// duration (1-52 weeks) and frequency (1-7 days) of a plan. Empty strings and
// zero numbers mean "not set".
func ValidateCatalogMetadata(level, trainingType string, durationWeeks, frequencyPerWeek int) error {
	if level = strings.TrimSpace(level); level != "" && !contains(LevelValues, level) {
		return fmt.Errorf("%w: invalid audience level", ErrInvalid)
	}
	if trainingType = strings.TrimSpace(trainingType); trainingType != "" && !contains(TrainingTypeValues, trainingType) {
		return fmt.Errorf("%w: invalid training type", ErrInvalid)
	}
	if durationWeeks < 0 || durationWeeks > 52 {
		return fmt.Errorf("%w: duration must be between 1 and 52 weeks", ErrInvalid)
	}
	if frequencyPerWeek < 0 || frequencyPerWeek > 7 {
		return fmt.Errorf("%w: frequency must be between 1 and 7 days per week", ErrInvalid)
	}
	return nil
}

// OptionalString maps an empty string to nil.
func OptionalString(value string) *string {
	value = strings.TrimSpace(value)
	if value == "" {
		return nil
	}
	return &value
}

// OptionalPositive maps a non-positive number to nil.
func OptionalPositive(value int) *int {
	if value <= 0 {
		return nil
	}
	return &value
}

func contains(values []string, value string) bool {
	for _, candidate := range values {
		if candidate == value {
			return true
		}
	}
	return false
}
